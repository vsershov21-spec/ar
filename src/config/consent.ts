/**
 * Согласие на быстром входе (feature 'intro.quick', src/quick): ОДНО место, которое меняют юристы — без правки кода
 * экрана. Значение попадает в заставку при сборке (vite.config.ts → src/quick/splash.ts), переопределить на сборке
 * можно переменной VITE_CONSENT_MODE=notice|checkbox|parent.
 *
 *   notice   — по умолчанию: только плашка под кнопкой («обрабатывается в телефоне…» + ссылка на условия), без галочек;
 *   checkbox — галочка «Согласен с условиями» над кнопкой; пока не отмечена, кнопка «Узнать, кто там» не нажимается;
 *   parent   — то же, но галочка «Я взрослый / родитель разрешил».
 *
 * Тексты — черновик для согласования с юристами Сбера (docs/PRIVACY.md, раздел «Быстрый вход»), нормы права здесь
 * не утверждаются.
 */
export type ConsentMode = 'notice' | 'checkbox' | 'parent';
export const CONSENT_MODES: readonly ConsentMode[] = ['notice', 'checkbox', 'parent'];

/** ← юристы: поменять здесь (или VITE_CONSENT_MODE на сборке) */
export const CONSENT_MODE_DEFAULT: ConsentMode = 'notice';

export const parseConsentMode = (v: string | undefined | null): ConsentMode => (CONSENT_MODES.includes(v as ConsentMode) ? (v as ConsentMode) : CONSENT_MODE_DEFAULT);

