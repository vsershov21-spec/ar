// Текст для синтеза речи (Piper, ElevenLabs): то, что показываем в пузыре, иногда читается не так.
// Латиница в названиях — по-русски, «ё» не трогаем. Субтитры и липсинк берут исходный текст,
// синтез и фонемы — этот. Меняете таблицу — меняется хэш только у затронутых реплик.
const RULES = [
  [/СберKids/g, 'Сбер Кидс'],
  [/Сбер ID/g, 'Сбер Ай Ди'],
];
export const spoken = (t) => RULES.reduce((s, [re, to]) => s.replace(re, to), t);
